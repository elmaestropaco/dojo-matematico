const fs = require('node:fs');
const path = require('node:path');
const { validateBank } = require('./validar-banco.cjs');
const plantillas = ['sumas.json', 'restas.json', 'multiplicaciones.json', 'divisiones.json', 'combinados.json'].flatMap(file => {
  const bank = JSON.parse(fs.readFileSync(path.join(__dirname, file), 'utf8'));
  const examples = validateBank(bank);
  const lines = [`# ${bank.plantillas.length} plantillas: ${file.replace('.json', '')}`, '', `Contenido editable: ${file}. Los marcadores entre llaves son variables.`, ''];
  bank.plantillas.forEach((template, index) => {
    lines.push(`## ${index + 1}. ${template.titulo}`, `ID: ${template.id} | Dificultad: ${template.dificultad || 'facil'}`, '', template.enunciado, '', '| Variable | Valores o significado |', '| --- | --- |');
    for (const [name, variable] of Object.entries(template.variables)) {
      const info = variable.tipo === 'entero' ? `${variable.descripcion}: de ${variable.minimo} a ${variable.maximo}.` : variable.tipo === 'texto' ? variable.valores.join(', ') : `${variable.singular} / ${variable.plural}, segun ${variable.cantidad}.`;
      lines.push(`| {${name}} | ${info} |`);
    }
    lines.push('', '### Ejemplo resuelto', '', examples[index].enunciado, '', ...examples[index].explicaciones.map(text => '- ' + text), '', `Respuesta: **${examples[index].respuesta}**.`, '');
  });
  fs.writeFileSync(path.join(__dirname, `VISTA-PREVIA-${file.replace('.json', '').toUpperCase()}.md`), lines.join('\n'), 'utf8');
  return bank.plantillas;
});
const bank = { version: 1, idioma: 'es', plantillas };
validateBank(bank);
fs.writeFileSync(path.join(__dirname, 'datos.js'), `// Generated by compilar-banco.cjs from the editable JSON banks.\nglobalThis.NinjaProblemBank = ${JSON.stringify(bank, null, 2)};\n`, 'utf8');
const names = { suma: 'Sumas', resta: 'Restas', multiplicacion: 'Multiplicaciones', division: 'Divisiones' };
const categories = Object.keys(names);
const counts = ['# Recuento del banco de problemas', '', '| Tipos de operaciones en el problema | Plantillas |', '| --- | ---: |'];
for (let mask = 1; mask < 16; mask++) {
  const selected = categories.filter((_, i) => mask & (1 << i));
  const count = plantillas.filter(t => t.etiquetas.length === selected.length && t.etiquetas.every(k => selected.includes(k))).length;
  counts.push(`| ${selected.map(k => names[k]).join(' + ')} | ${count} |`);
}
counts.push(`| **Total** | **${plantillas.length}** |`, '', 'Generado con `node banco-problemas/compilar-banco.cjs`. Cada plantilla se cuenta una sola vez, segun sus etiquetas.', '');
fs.writeFileSync(path.join(__dirname, 'RECUENTO.md'), counts.join('\n'), 'utf8');
console.log(`Banco compilado: ${plantillas.length} plantillas.`);
const advanced = JSON.parse(fs.readFileSync(path.join(__dirname, 'ampliado.json'), 'utf8'));
const ids = new Set();
for (const t of advanced.plantillas) {
  if (!t.id || ids.has(t.id) || !['fracciones', 'mcmMcd'].includes(t.family) || !t.scene?.intro || !t.scene?.unit || !t.categories?.length) throw Error('Plantilla ampliada no valida: ' + t.id);
  ids.add(t.id);
  if (t.family === 'fracciones' && (t.categories.some(k => !categories.includes(k)) || t.order.length !== t.categories.length || new Set(t.order).size !== t.categories.length || t.order.some(k => !t.categories.includes(k)))) throw Error('Operaciones no validas: ' + t.id);
  if (t.family === 'mcmMcd' && t.categories.some(k => !['mcm', 'mcd'].includes(k))) throw Error('Tipos MCM/MCD no validos');
}
fs.writeFileSync(path.join(__dirname, 'ampliado-datos.js'), `// Generated by compilar-banco.cjs from ampliado.json.\nglobalThis.NinjaAdvancedProblemBank = ${JSON.stringify(advanced, null, 2)};\n`);
const advancedCounts = new Map();
for (const t of advanced.plantillas) { const key = t.family + ': ' + [...t.categories].sort().join(' + '); advancedCounts.set(key, (advancedCounts.get(key) || 0) + 1); }
counts.push('## Familias ampliadas', '', '| Familia y tipos | Plantillas |', '| --- | ---: |', ...[...advancedCounts].map(([key, count]) => `| ${key} | ${count} |`), '', `Total de la app: **${plantillas.length + advanced.plantillas.length} plantillas**.`, '');
fs.writeFileSync(path.join(__dirname, 'RECUENTO.md'), counts.join('\n'), 'utf8');
console.log(`Banco ampliado compilado: ${advanced.plantillas.length} plantillas. Total: ${plantillas.length + advanced.plantillas.length}.`);
globalThis.NinjaAdvancedProblemBank = advanced;
const engine = require('../problemas.js');
require('../matematicas-extra.js');
const groups = new Map(), rendered = new Map();
for (const t of advanced.plantillas) { const key = t.family + ':' + [...t.categories].sort().join(','); if (!groups.has(key)) groups.set(key, t); }
for (const t of groups.values()) {
  const settings = { ...Object.fromEntries(categories.map(k => [k, { enabled: t.categories.includes(k) }])), _family: t.family, _mcmEnabled: t.categories.includes('mcm'), _mcdEnabled: t.categories.includes('mcd') };
  const options = { mix: t.categories.length > 1 ? 'combinados' : 'individuales' };
  const pool = engine.compatible(settings, options);
  for (let i = 0; i < pool.length; i++) { const op = engine.generate(settings, i, 123, options); rendered.set(op.problem.templateId, op); }
}
const preview = ['# Ejemplos del banco ampliado', '', 'Generados con cantidades de ejemplo. Los datos cambian en cada partida; no son cantidades fijas.', ''];
for (const t of advanced.plantillas) {
  const op = rendered.get(t.id);
  if (!op) throw Error('Plantilla sin ejemplo generado: ' + t.id);
  const answer = op.answerFraction ? `${op.answerFraction.numerator}/${op.answerFraction.denominator}` : op.answerExact;
  preview.push(`## ${t.title}`, `ID: ${t.id} | Familia: ${t.family} | Tipos: ${t.categories.join(', ')}`, '', op.problem.text, '', ...op.problem.steps.map(s => '- ' + s), '', `Respuesta: **${answer} ${op.problem.unit}**.`, '');
}
fs.writeFileSync(path.join(__dirname, 'VISTA-PREVIA-AMPLIADO.md'), preview.join('\n'), 'utf8');
